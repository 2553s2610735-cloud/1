import streamlit as st
import random

# 1. 앱 제목과 간단한 설명
st.title("🍕 오늘 뭐 먹지? 초간단 음식 추천기")
st.write("메뉴 고르기 귀찮으시죠? 지금 기분에 딱 맞는 음식을 추천해 드릴게요!")

# 2. 사용자 기분 선택 (드롭다운 메뉴)
mood = st.selectbox(
    "지금 어떤 기분이신가요?",
    ["배고파서 쓰러질 것 같다", "매콤한 게 당긴다", "가볍고 깔끔한 게 좋다", "달달한 게 필요하다"]
)

# 3. 기분별 음식 데이터 (딕셔너리 구조)
food_dict = {
    "배고파서 쓰러질 것 같다": ["삼겹살", "돈가스", "짜장면+탕수육", "뼈해장국"],
    "매콤한 게 당긴다": ["떡볶이", "마라탕", "불닭", "낙지볶음"],
    "가볍고 깔끔한 게 좋다": ["초밥", "샐러드", "쌀국수", "샌드위치"],
    "달달한 게 필요하다": ["와플", "초코 케이크", "탕후루", "크로플"]
}

# 4. 추천 버튼 및 결과 출력
if st.button("오늘의 메뉴 추천받기 ✨"):
    # 사용자가 고른 기분에 해당하는 리스트에서 무작위로 하나 추출
    selected_food = random.choice(food_dict[mood])
    
    # 초록색 성공 박스로 결과 표시
    st.success(f"오늘 저녁은 바로... **{selected_food}** 어떠세요? 맛있게 드세요! 😋")
